#include <string>
#include <vector>

// ---------------------------------------------------------------------------
// 歌词文件本地搜索
//
// 为什么需要它：原先「同目录 + 同文件名 + .lrc」的推导（lyric.cpp 的
// MakeLyricPathForAudio）只覆盖最理想的一种摆放。实测最常见的失败长这样：
//
//     音频：D:\music\塞壬唱片-MSR - Battleplan Obliteration.wav
//     歌词：D:\music\Battleplan Obliteration.lrc
//
// 文件名前多出一段「厂牌 - 」前缀，精确匹配必然落空 —— 歌是找到了的，
// 只是名字被人动过手脚。所以匹配要做成**多策略 + 置信度打分**，
// 而不是一刀切的真假判断。
//
// ---------------------------------------------------------------------------
// 计分与选择
//
// 分数不是装饰，是**取舍的依据**：调用方（以及未来可能的「候选列表」界面）
// 需要知道这个结果有多可信。各策略的档次：
//
//     100  精确       同 stem
//      90  去前缀     从音频 stem 的某个「 - 」切点右侧取候选
//      85  去前缀     从切点左侧取候选
//      80  标签构造   artist/title 拼出的候选（仅 cfg.useTags 为真时）
//     76+ 模糊       归一化相似度达到阈值后按比例折算
//
// 命中额外目录（cfg.extraDir）的**同类匹配一律减 5** —— 同目录是原生位置，
// extraDir 是集中存放的备胎，两者同时存在时必须优先同目录那一份。
//
// 最终的返回值**只按分数取最高**，与策略的先后顺序无关；
// 所以调用方不必关心内部是「先精确后模糊」还是反过来。
// ---------------------------------------------------------------------------
//
// 【硬约束】错误的歌词比找不到更糟 —— 一首歌配错词是持续可见的错误，
// 而没找到只是没显示。所以模糊匹配只有在相似度**确实达标**时才接受，
// 宁可返回空结果。所以命中结果里带着 how 与 score，便于现场排查误配。
// ---------------------------------------------------------------------------

namespace lyricus {

struct LyricSearchHit {
    std::wstring path;        // 命中的文件全路径；空 = 没找到
    int          score = 0;   // 0..100，越大越可信
    std::wstring how;         // 命中方式，写日志用：exact / prefix-strip / tagged / fuzzy
};

// 在音频文件附近（同目录 + 可选 extraDir）查找歌词文件，返回得分最高的一条。
//
// audioPath: 音频文件全路径（本地文件系统路径，不是 file:// URL）
// artist/title/album: 来自标签，可为空
// cfg: 由调用方传 GetLyricSearchConfig() 的结果
//
// 所有参数只读；不做任何文件写操作。内部不抛异常 —— 目录不存在、
// 文件名超长、空文件之类的情况一律降级为「没找到」。
LyricSearchHit FindLyricFile(const std::wstring& audioPath,
                             const std::wstring& artist,
                             const std::wstring& title,
                             const std::wstring& album,
                             const LyricSearchConfig& cfg);

// 文件名归一化（去路径与扩展名、统一大小写、全角折半角、剔除标点与空白、
// 折叠连续空白），供复用与调试。
//
// 传文件名或全路径都行。之所以是**折叠**空白而不是删光：英文曲名靠空格分词，
// 删光会让 "love me" 与 "loveme" 变成同一个东西。
std::wstring NormalizeLyricStem(const std::wstring& name);

// 把一个名字切成「可能是曲名」的候选集合：原样，加上每个 " - " 切点的左右两侧。
//
// 【为什么要把这个切法单独暴露出来】
// **在线歌词的核对必须用同一套切法**。
// 文件没有标签时，foobar2000 的 %title% 会退化成**文件名**（形如 "Artist - Title"），
// 而 LRCLIB 的 trackName 往往只有 "Title" ——
// 不切一刀就永远对不上，会把**本来正确**的搜索结果误判成"张冠李戴"丢掉。
//
// 这不是假想：实测拿一个无标签的「周杰伦 - 晴天.wav」跑在线查询，
// LRCLIB 返回的就是正确的「周杰伦 - 晴天 / 270.0 秒」，
// 却因为本地曲名带着前缀而被拒绝。见 D-027。
//
// 两处要是各写一套切法，就会变成「搜索按 A 切法找到了、核对按 B 切法又否掉」
// 这种自相矛盾，所以这里直接复用搜索模块内部那一份。
std::vector<std::wstring> MakeTitleCandidates(const std::wstring& name);

// 这个"标签值"其实是 foobar2000 对**没有这个字段**的占位符，不是真的名字。
//
// 【为什么必须单独判】用户那批无标签的 WAV，%artist% 渲染出来是字面的「?」，
// 而 %artist% 在另一些情况下是「未知艺术家」。这些都不是歌手名 ——
// 拿它们去搜、去比对，只会污染搜索结果并让演唱者判定永远失败。
//
// 实测的发源地：`E:\奇爱人生·终焉版\本体\02 遗忘山丘.wav`，日志里是
//     标签=[?] - [02 遗忘山丘]
// 于是我们拿「?」当歌手发出去查，返回的 5 条里后 4 条直接被带偏成
// 「青山不改与君携」「一如既往」这类完全不相干的结果。
//
// 判据故意**只认这几个确切的占位符**，不做"看起来像不像名字"的猜测 ——
// 猜错会把真的歌手名当占位符丢掉。
bool IsPlaceholderTag(const std::wstring& s);

// 去掉曲名开头的音轨号：「02 遗忘山丘」->「遗忘山丘」。切不动就原样返回。
//
// 【为什么需要单独导出】在线查询的**搜索词**必须用它。
// 实测（2026-09-24）拿带音轨号的词去搜网易云会被整个带偏：
//     查「02 遗忘山丘」 -> 青山不改与君携 / 讨好 / 遗憾 …（正确答案连前 6 都进不去）
//     查「遗忘山丘」    -> 遗忘山丘 by 阿良良木健（242.8s，本地 242.1s，差 0.7 秒）
// 我们原来只在**候选核验**里剥音轨号、搜索词没剥，于是第一关就搜错了东西，
// 后面的闸门再对也没用。
//
// 分隔符必须是空格/点/横线/下划线/顿号之一，且数字最多 3 位 ——
// 否则「24K Magic」「7 Years」这类**以数字开头的曲名**会被切坏。
std::wstring StripLeadingTrackNumber(const std::wstring& name);

// 从音频路径猜一个"专辑线索"给在线搜索用。猜不出返回空串。
//
// 【为什么是文件夹名】用户那批专辑一个标签都没打，但**文件夹名往往就是专辑名**：
//     E:\奇爱人生·终焉版\本体\02 遗忘山丘.wav   -> 线索「奇爱人生·终焉版」
//     D:\再见，碳酸海\2 世界第一可爱.flac       -> 线索「再见，碳酸海」
// 实测带上它之后搜索质量明显变好（`查「奇爱人生 遗忘山丘」` 命中，
// 而 `查「02 遗忘山丘」` 里正确答案连前 6 都进不去）。
//
// 【为什么要往上走一层】很多专辑会套一个通用子目录：
//     E:\奇爱人生·终焉版\**本体**\...
//     E:\恋爱理论\**数字版**\...
// 直接取文件夹名会拿到「本体」「数字版」这种毫无信息量的词，反而污染搜索。
// 所以命中一张通用名表就再往上走一层。
//
// ⚠️ 这只是**猜测**，只做搜索词加成，**不参与**曲目身份判定，也**不进**缓存键。
//    用户要能覆盖它（见 docs/plan.md #10 的用户入口）。
std::wstring GuessAlbumHintFromPath(const std::wstring& filePath);

// 两个演唱者名字有没有交集。
//
// 【为什么要单独导出一个】两处在用：网易云候选的挑选（online_lyric.cpp）
// 和在线结果回到播放器后的核对（playback_state.cpp）。
// 各写一套的话，就会出现「挑的时候按 A 判、核对的时候按 B 判」，
// 表现是「明明候选里有人对得上，结果还是被丢掉了」——极难排查。
//
// 处理的是真实数据里的多人和分隔符差异：
//   * 网易云用 '/' 分隔多人（`阿良良木健/洛天依/乐正绫`），
//     而本地标签可能用「、」（`苍十三、阿良良木健`）；
//   * 一方带前缀/后缀（`叶秋池、阿良良木健` vs `阿良良木健`）——
//     用"包含"而不是"相等"来兜住。
//
// ⚠️ **明确不做繁简转换**。实测：
//     本地标签「純白P」（繁体純） vs 网易云「Soda纯白」（简体纯）
//   归一化后是 `純白p` 和 `soda纯白`，**没有任何公共子串**，这个函数返回 false。
//   那种情况靠的是调用方的**时长闸**（实测那几条时长差 0 秒），
//   而不是这里 —— 别把这条注释改成"能兜住繁简"，
//   那是个不成立的说法（我自己先写错了一次，被单测抓出来）。
//
// 任一为空返回 false —— 没有信息就不算对上，由调用方决定要不要放行。
bool ArtistNamesOverlap(const std::wstring& a, const std::wstring& b);

} // namespace lyricus
