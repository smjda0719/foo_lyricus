#pragma once

#include <windows.h>

// ---------------------------------------------------------------------------
// 颜色工具 —— **纯函数**，不依赖 SDK，所以能进离线单测台。
//
// 【为什么单独一层】`BlendColor` 曾经在四个地方各有一份：
//   dui_element.cpp / cui_panel.cpp（都是 float 版）、ui_draw.cpp（double 版）、
//   以及 prefs_layout.cpp 里一个改名叫 Blend 的。plan.md 的"已知小问题"里
//   一直记着"该提到公共层"。
//
// 它**不能**挂在 ui_draw.h 上 —— 那个文件要取宿主主题、依赖 SDK，
// 而 prefs_layout（布局与配色推导）必须保持无 SDK 才能进单测台。
// 所以工具归这里，界面归 ui_draw，两边都 include 这一份。
// ---------------------------------------------------------------------------

namespace lyricus {

// 按 t 把 a 与 b 混合：t=0 全取 a，t=1 全取 b。
//
// t **可以是负数或大于 1** —— 那是**外推**，用来把结果推得比两端更远。
// dui_element.cpp 就靠 `BlendColor(normalText, background, -0.5)` 让当前行
// 比正文色更亮（往背景的反方向推）。合并这几份实现时特意保留了这个能力，
// 否则那份调用会被静默改成"夹在两端之间"，看起来只是"高亮没了"。
//
// 结果按分量 clamp 到 0..255（外推很容易越界）。
COLORREF BlendColor(COLORREF a, COLORREF b, double t);

// 感知亮度 0..255。加权而不是简单平均 —— 纯蓝和纯黄的"平均"一样，
// 人眼看上去差得远。自绘时用它判断"这个底色上该压黑字还是白字"。
int ColorLuminance(COLORREF c);

// ---------------------------------------------------------------------------
// 控制条配色（D-093）
// ---------------------------------------------------------------------------

// 控制条的 4 个**基色**。控制条上一共有 11 类颜色，这里只放 4 个 ——
// 组内其余（悬停 / 按下 / 轨道 / 主操作图标）由基色推出来。
struct ControlBaseColors {
    COLORREF button = RGB(58, 62, 72);     // 按钮底
    COLORREF icon   = RGB(200, 200, 208);  // 图标
    COLORREF slider = RGB(206, 210, 220);  // 滑块填充
    COLORREF text   = RGB(190, 190, 198);  // 时间文字
};

// 从**面板底色**推导出这 4 个基色 —— 也就是"自动"模式下的实际配色。
//
// 【为什么必须共用一份实现】有两处要用它：
//   1. control_window.cpp 的 DrawControls / DrawIconOverlay —— 自动模式的实际取色；
//   2. prefs_page.cpp —— 用户从「自动」切到「自定义」时，要把这 4 个基色
//      预填成**当前看起来的样子**，这样切换是**无损**的。
// 两处各写一遍的话，它们会在某次调参后悄悄分叉，用户一按「自定义」
// 颜色就跳一下 —— 而没人会想到原因是"两个地方算得不一样"。
ControlBaseColors DeriveControlColors(COLORREF panelBg);

// 把一个基色按"远离它自己"的方向推一档，用来生成悬停 / 按下 / 轨道那几档。
//
// ⚠️ 方向由**基色自己的亮度**决定，不是面板底色：亮基色往暗走、暗基色往亮走。
//    自定义模式下用户完全可能在深底上放一个亮按钮 ——
//    那时用"面板是深色所以往亮推"的规则，悬停就什么都看不出来。
COLORREF ShiftControlColor(COLORREF base, double t);

} // namespace lyricus
