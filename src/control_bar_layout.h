#pragma once

#include <windows.h>

// ---------------------------------------------------------------------------
// 控制条的**布局数学** —— 纯函数：给一块矩形和 DPI，算出一组控件矩形。
//
// 【为什么单独抽出来】这段逻辑 2026-09-26 一天之内改了两轮，而两轮都只能
// 靠"把数算一遍 + 截图看"来验证：
//   * 第一轮：横向拖窄时进度条被挤没 —— 判据 `progR > progL + S(40)` 一不成立
//     就整条不画，而用户那块 832 物理像素的面板正好卡在 `340 > 340` 为假；
//   * 第二轮：改成按优先级降级之后，还要保证被降级掉的空矩形不会在
//     客户区左上角画出鬼影（`x = left + (宽 - iconW)/2` 会算出负数）。
//
// 而"给定宽度 -> 一组矩形"恰恰是单测台最擅长钉的东西：遍历几十种宽度，
// 断言不重叠、不越界、进度条不消失。放在 ControlWindow 里就只能靠人眼。
//
// 本文件**不依赖 SDK**（只要 windows.h 的 RECT / MulDiv），
// 所以能进 tests/harness 那套 shim 单测台（见 run.ps1 的 cbar 组）。
// ---------------------------------------------------------------------------

namespace lyricus {

// 控制条上各控件的位置。
//
// 【怎么表示"这一项被降级掉了"】用**空矩形**（`right <= left`）。
// 调用方（绘制 / 命中测试）一律先判这个再动手 —— 这一条是硬约定：
// 绘制侧原先对时间 / 音量图标 / 音量条是无条件画的，空矩形会让它们
// 算出负坐标、在图坐标左上角画出半个图标。
struct ControlBarRects {
    RECT prev{};
    RECT playPause{};
    RECT next{};
    RECT progress{};     // 空 = 不画。只有面板窄到连三个按钮都放不下时才会空
    RECT time{};         // 空 = 放不下，已牺牲
    RECT volumeIcon{};   // 静音开关：不参与降级，但极窄时也可能被收掉
    RECT volumeBar{};    // 空 = 放不下，已牺牲
    int  barTop = 0;     // 控制条上沿 = 歌词区的下界（不是控件，但要一起算）
};

// 算出控制条各控件的位置。rc 是**客户区**矩形，dpi 用于逻辑像素换算。
//
// 【降级顺序】面板变窄时按这个顺序丢东西，越靠后越先丢：
//
//     三个走带按钮（固定） > 进度条 > 时间 > 音量条
//
// 理由见 .cpp —— 一句话：**滚轮能替代音量条，替代不了进度和时间**。
ControlBarRects ComputeControlBarLayout(const RECT& rc, int dpi);

} // namespace lyricus
