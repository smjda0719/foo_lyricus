// 组件版本号 —— **唯一来源**。
//
// 【为什么要单独一个头】两个地方要用它：
//   * main.cpp 的 DECLARE_COMPONENT_VERSION —— foobar2000 组件列表里显示的那个
//   * initquit.cpp 启动时打进日志的「构建标识」
// 两处各写一份的话迟早会不一致，而"版本对不上"恰恰是这个号最不该出的问题。
//
// 【为什么它不能代替构建标识】这个号是**手工维护**的：热安装换掉 DLL 之后，
// 组件列表里显示的仍然是上一次写下的字符串。2026-09-26 就因此误判过一次
// "好像没安上"——DLL 分明是新的，列表里却看不出任何变化。
// 所以 initquit.cpp 还会额外打一条 **DLL 文件写入时间**，那个每编译一次必变，
// 是判断"跑的是哪一份"的硬证据。
//
// 改动有感时顺手升一位（M0 起一直是 0.1.0，到 D-058 才升 0.2.0）。
// ---------------------------------------------------------------------------

